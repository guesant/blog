import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as simpleIcons from 'simple-icons';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(scriptDir, '..', 'resources', 'php', 'brand-icons.php');

const slugs = [
  'github',
  'gitlab',
  'orcid',
  'googlescholar',
  'bluesky',
  'instagram',
  'mastodon',
  'researchgate',
];

const bySlug = new Map();
for (const key of Object.keys(simpleIcons)) {
  const icon = simpleIcons[key];
  if (icon && typeof icon === 'object' && icon.slug) {
    bySlug.set(icon.slug, icon);
  }
}

const entries = [];
for (const slug of slugs) {
  const icon = bySlug.get(slug);
  if (!icon) {
    console.warn(`No simple-icons match for ${slug}`);
    continue;
  }
  entries.push(`    '${slug}' => ['path' => '${icon.path}', 'title' => ${JSON.stringify(icon.title)}],`);
}

const php = `<?php

// Generated by tools/generate-brand-icons.mjs from the simple-icons npm
// package. Social platform glyphs for contact/profile links, mirroring the
// legacy app's BrandIcon component. Rendered with fill=currentColor (not
// brand color) to match the legacy footer/nav styling.

return [
${entries.join('\n')}
];
`;

writeFileSync(outFile, php, 'utf8');
console.log(`Wrote ${entries.length} icons to ${path.relative(process.cwd(), outFile)}`);
