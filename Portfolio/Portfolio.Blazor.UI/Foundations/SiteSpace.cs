namespace Portfolio.Blazor.UI.Foundations;

/// <summary>Spacing scale used by layout primitives for gaps.</summary>
public enum SiteSpace
{
    /// <summary>No gap.</summary>
    None,

    /// <summary>Tightest gap.</summary>
    Xs,

    /// <summary>Gap between closely related items.</summary>
    Sm,

    /// <summary>Default gap.</summary>
    Md,

    /// <summary>Gap between groups.</summary>
    Lg,

    /// <summary>Gap between sections.</summary>
    Xl,

    /// <summary>Widest gap.</summary>
    Xxl,
}
