namespace Blog.Blazor.UI.Foundations;

/// <summary>Height and density of a button or button-like link.</summary>
public enum SiteButtonSize
{
    /// <summary>24px, for dense inline actions.</summary>
    Xs,

    /// <summary>32px, the compact default.</summary>
    Sm,

    /// <summary>36px, the standard control height.</summary>
    Default,

    /// <summary>40px, for prominent actions.</summary>
    Lg,

    /// <summary>Square 24px, icon only.</summary>
    IconXs,

    /// <summary>Square 32px, icon only.</summary>
    IconSm,

    /// <summary>Square 36px, icon only.</summary>
    Icon,

    /// <summary>Square 40px, icon only.</summary>
    IconLg,
}
