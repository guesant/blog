import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(scriptDir, '..', 'resources', 'php', 'phosphor-icons.php');
const style = 'regular';
const phosphorDir = path.join(scriptDir, '..', 'node_modules', '@phosphor-icons', 'core', 'assets', style);

const names = [
  'map-pin',
  'user',
  'flag',
  'target',
  'compass',
  'calendar',
  'calendar-blank',
  'clock',
  'buildings',
  'copy-simple',
  'file-text',
  'barcode',
  'hash-straight',
  'newspaper-clipping',
  'users',
  'git-branch',
  'translate',
  'certificate',
  'television',
  'play',
  'identification-badge',
  'film-slate',
  'wrench',
];

const entries = [];
for (const name of names) {
  const svg = readFileSync(path.join(phosphorDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim();
  entries.push(`    '${name}' => ${JSON.stringify(inner)},`);
}

const php = `<?php

// Generated by tools/generate-phosphor-icons.mjs from the @phosphor-icons/core
// npm package (regular style). Inner SVG markup per icon, rendered inline by
// the x-site.icon Blade component with set="phosphor" and fill=currentColor.

return [
${entries.join('\n')}
];
`;

writeFileSync(outFile, php, 'utf8');
console.log(`Wrote ${entries.length} icons to ${path.relative(process.cwd(), outFile)}`);
