namespace Blog.Blazor.UI.Foundations;

/// <summary>Text styles rendered by SiteText.</summary>
public enum SiteTextVariant
{
    /// <summary>Default running text.</summary>
    Body,

    /// <summary>Smaller supporting text.</summary>
    Small,

    /// <summary>Uppercase label above a heading.</summary>
    Eyebrow,

    /// <summary>Uppercase label introducing a section.</summary>
    SectionLabel,

    /// <summary>Larger introductory paragraph.</summary>
    Lead,

    /// <summary>Muted metadata.</summary>
    Meta,

    /// <summary>Truncated summary of longer content.</summary>
    Excerpt,

    /// <summary>The number in a metric.</summary>
    MetricValue,

    /// <summary>The caption under a metric.</summary>
    MetricLabel,
}
