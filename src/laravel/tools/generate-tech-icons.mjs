import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as simpleIcons from 'simple-icons';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const slugsFile = path.join(scriptDir, 'tech-logo-slugs.json');
const outFile = path.join(scriptDir, '..', 'resources', 'php', 'tech-icons.php');

const slugs = JSON.parse(readFileSync(slugsFile, 'utf8'));

const bySlug = new Map();
for (const key of Object.keys(simpleIcons)) {
  const icon = simpleIcons[key];
  if (icon && typeof icon === 'object' && icon.slug) {
    bySlug.set(icon.slug, icon);
  }
}

const missing = [];
const entries = [];
for (const slug of slugs) {
  const icon = bySlug.get(slug);
  if (!icon) {
    missing.push(slug);
    continue;
  }
  entries.push(`    '${slug}' => ['path' => '${icon.path}', 'hex' => '${icon.hex}', 'title' => ${JSON.stringify(icon.title)}],`);
}

if (missing.length > 0) {
  console.warn('No simple-icons match for slugs:', missing.join(', '));
}

const php = `<?php

// Generated by tools/generate-tech-icons.mjs from the simple-icons npm
// package (same version used by the legacy Next.js app). Self-hosted SVG
// path data + brand color per technology, keyed by the slug already
// stored on Technology.logo in the database. Re-run the generator if new
// technologies with a \`logo\` value are added.

return [
${entries.join('\n')}
];
`;

writeFileSync(outFile, php, 'utf8');
console.log(`Wrote ${entries.length} icons to ${path.relative(process.cwd(), outFile)}`);
