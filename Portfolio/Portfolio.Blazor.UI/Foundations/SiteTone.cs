namespace Portfolio.Blazor.UI.Foundations;

/// <summary>Semantic color tone shared by feedback and status components.</summary>
public enum SiteTone
{
    /// <summary>No semantic meaning.</summary>
    Neutral,

    /// <summary>Informational.</summary>
    Info,

    /// <summary>Something worked.</summary>
    Success,

    /// <summary>Needs attention.</summary>
    Warning,

    /// <summary>Something failed or is destructive.</summary>
    Danger,
}
