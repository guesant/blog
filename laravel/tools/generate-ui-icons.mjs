import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(scriptDir, '..', 'resources', 'php', 'ui-icons.php');
const lucideDir = path.join(scriptDir, '..', 'node_modules', 'lucide-static', 'icons');

const names = [
  'arrow-right',
  'arrow-left',
  'arrow-up-right',
  'menu',
  'x',
  'mail',
  'file-text',
  'external-link',
  'briefcase',
  'layout-grid',
  'pen-line',
  'sparkles',
  'user',
  'graduation-cap',
  'home',
  'circle-help',
  'lightbulb',
  'git-branch',
  'globe',
  'book-open',
  'play-circle',
  'shopping-cart',
  'download',
  'folder-git-2',
  'languages',
  'archive',
  'star',
  'messages-square',
  'building-2',
  'more-horizontal',
  'chevron-down',
  'copy',
  'check',
  'search',
  'list',
  'layout-list',
  'activity',
  'maximize',
  'percent',
  'divide',
  'sigma',
  'ruler',
  'scale',
  'blend',
  'layers',
  'contrast',
  'eye',
  'move-horizontal',
  'square-round-corner',
  'palette',
];

const entries = [];
for (const name of names) {
  const svg = readFileSync(path.join(lucideDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim();
  entries.push(`    '${name}' => ${JSON.stringify(inner)},`);
}

const php = `<?php

// Generated by tools/generate-ui-icons.mjs from the lucide-static npm
// package (the same Lucide icon set the legacy Next.js app used via
// lucide-react). Inner SVG markup per icon, rendered inline by the
// x-site.icon Blade component with stroke=currentColor.

return [
${entries.join('\n')}
];
`;

writeFileSync(outFile, php, 'utf8');
console.log(`Wrote ${entries.length} icons to ${path.relative(process.cwd(), outFile)}`);
